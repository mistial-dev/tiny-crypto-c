/* AES key wrap known answers on an emulated ATmega328P: RFC 3394 section 4.1,
 * KWP round trips on the single-block and W paths, and Wycheproof
 * aes_wrap_test.json tcId 10, whose step counter reaches 288 and so uses the
 * high byte of the 16-bit size_t. The result is written to USART0 as KW-OK or
 * KW-BAD. */
#include <avr/io.h>
#include <avr/pgmspace.h>
#include <string.h>
#include <tiny_crypto/aes_kw.h>

static void put_string(const char* text)
{
  while (*text) {
    while (!(UCSR0A & (1 << UDRE0))) {
    }
    UDR0 = (uint8_t)*text++;
  }
}

