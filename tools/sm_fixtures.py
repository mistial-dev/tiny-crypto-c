def _session(bits, certificate, confirmation, command_mac, response_mac, intermediate=b""):
    public = bytes.fromhex(ANSWERS[bits][0])
    width = bits // 8
    key_length = 16 if bits == 256 else 32
    suite = 0x27 if bits == 256 else 0x2e
    nonce = bytes(range(16 if bits == 256 else 24))
    card_id = hashlib.sha256(certificate).digest()[:8]
    other = (bytes([4] + [9 if bits == 256 else 13] * 4 + [8]) + bytes(8) +
             bytes.fromhex("010010") + public[1:17] + bytes([8]) + card_id +
             bytes([len(nonce)]) + nonce + bytes.fromhex("0100"))
    digest = hashlib.sha256 if bits == 256 else hashlib.sha384
    material = b"".join(digest(i.to_bytes(4, "big") + public[1:1 + width] + other).digest()
                        for i in range(1, 4))[:4 * key_length]
    body = tlv(0x7c, tlv(0x81, bytes(9) + public) + tlv(0x82, b""))
    return {
        "public_key": public,
        "request": bytes([0, 0x87, suite, 4, len(body)]) + body + b"\0",
        "response": tlv(0x7c, tlv(0x82, b"\0" + nonce + confirmation + certificate)),
        "material": material,
        "command": tlv(0x8e, command_mac[:8]),
        "reply": tlv(0x99, bytes.fromhex("9000")) + tlv(0x8e, response_mac[:8]),
        "intermediate": intermediate,
    }


def session(bits):
    public, confirmation, command_mac, response_mac = map(bytes.fromhex, ANSWERS[bits])
    return _session(bits, cvc(bits, public), confirmation, command_mac, response_mac)


def chain_session(bits):
    public = bytes.fromhex(ANSWERS[bits][0])
    subject = hashlib.sha1(public).digest()[:8]
    intermediate = cvc(bits, public, subject=subject, role=0x12)
    certificate = cvc(bits, public, issuer=subject)
    confirmation, command_mac, response_mac = map(bytes.fromhex, CHAIN_ANSWERS[bits])
    return _session(bits, certificate, confirmation, command_mac, response_mac, intermediate)


