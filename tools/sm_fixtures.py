    import argparse
    from pathlib import Path
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    fields = ("public_key", "request", "response", "material", "command", "reply", "intermediate")
    lines = ["/* Generated by tools/sm_fixtures.py. */", "#include <tiny_crypto/piv_sm.h>"]
    for bits in (256, 384):
        for name, value in session(bits).items():
            if value:
                lines.append("static " + c_array(value, f"sm_{bits}_{name}"))
        for name, value in chain_session(bits).items():
            lines.append("static " + c_array(value, f"sm_{bits}_chain_{name}"))
    lines.append("struct tc_sm_fixture { TC_PIV_SM_suite suite; " +
                 " ".join(f"TC_bytes {name};" for name in fields) + " };")
    lines.append("static const struct tc_sm_fixture sm_fixtures[] = {")
    for bits in (256, 384):
        suite = "TC_PIV_SM_CS2" if bits == 256 else "TC_PIV_SM_CS7"
        lines.append("{" + suite + "," + ",".join(
            "{NULL,0}" if name == "intermediate" else
            f"{{sm_{bits}_{name},sizeof sm_{bits}_{name}}}" for name in fields) + "},")
        lines.append("{" + suite + "," + ",".join(
            f"{{sm_{bits}_chain_{name},sizeof sm_{bits}_chain_{name}}}" for name in fields) + "},")
    lines.append("};")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines) + "\n")
